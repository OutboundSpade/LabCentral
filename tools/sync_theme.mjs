import {readFile,writeFile} from 'node:fs/promises';
const theme=await readFile(new URL('../pkg/plugin-sdk-browser/theme.css',import.meta.url),'utf8');
const output='/* Generated by tools/sync_theme.mjs from the published browser SDK theme. */\n@import "tailwindcss" source(".");\n@plugin "daisyui" { themes: false; }\n'+theme;
const path=new URL('../web/src/app.css',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==output)throw new Error('Core theme differs from the published SDK theme');}
else await writeFile(path,output);
