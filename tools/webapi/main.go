// Generate the browser's public DTO contract from hosted types.
package main

import (
	"fmt"
	"github.com/OutboundSpade/LabCentral/v2/hosted"
	"github.com/OutboundSpade/LabCentral/v2/instructor"
	"os"
	"reflect"
	"strconv"
	"strings"
	"time"
)

func typ(t reflect.Type) string {
	if t == reflect.TypeOf(time.Time{}) {
		return "string"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int:
		return "number"
	case reflect.Pointer:
		return typ(t.Elem()) + " | null"
	case reflect.Slice:
		return typ(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, unknown>"
	case reflect.Struct:
		return dtoName(t)
	}
	panic(t.String())
}
func main() {
	var b strings.Builder
	b.WriteString("// Generated by go run ./tools/webapi. Do not edit.\n")
	for _, v := range []any{hosted.ImageSummary{}, hosted.ImagePruneOutcome{}, hosted.TemplateLibraryMetadata{}, hosted.TemplateScenarioSummary{}, hosted.CreateTemplateAttemptRequest{}, hosted.CoachMachines{}, hosted.User{}, hosted.Meeting{}, hosted.Team{}, hosted.Membership{}, hosted.Template{}, hosted.Job{}, hosted.Machine{}, hosted.Teammate{}, hosted.LabView{}, hosted.Overview{}, hosted.AdminView{}, hosted.TeamDesktopCount{}, hosted.CreateMeeting{}, hosted.JoinTeam{}, hosted.ExtendMeeting{}, hosted.TargetRequest{}, hosted.Launch{}, hosted.BreakDefinition{}, hosted.BreakRun{}, hosted.BreakRequest{}, hosted.InstructorView{}, hosted.CheckDefinition{}, hosted.CheckSchedule{}, hosted.CheckScheduleRequest{}, hosted.CheckRun{}, hosted.CheckResult{}, hosted.LearningStep{}, hosted.LearningStepInput{}, hosted.LearningPublication{}, hosted.LearningLab{}, hosted.LearningProgress{}, hosted.CloudQuota{}, hosted.PracticeRun{}, hosted.LearningCheck{}, hosted.LearningCatalog{}, hosted.LearningView{}, hosted.LearningAdminView{}, hosted.LearningAnswerRequest{}, hosted.LearningCheckRequest{}, hosted.TemplateStage{}, instructor.Completion{}, instructor.Answer{}, hosted.TemplateImportFailure{}, hosted.PublicTemplate{}, hosted.PublicTemplateMachine{}, hosted.TemplateCatalog{}, hosted.LearningSolutionRequest{}, hosted.LearningSolution{}} {
		t := reflect.TypeOf(v)
		fmt.Fprintf(&b, "export interface %s {\n", dtoName(t))
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			if tag[0] == "-" {
				continue
			}
			optional := ""
			if len(tag) > 1 && tag[1] == "omitempty" {
				optional = "?"
			}
			fieldType := typ(f.Type)
			if values := f.Tag.Get("enum"); values != "" {
				items := strings.Split(values, ",")
				for i, v := range items {
					items[i] = strconv.Quote(v)
				}
				fieldType = strings.Join(items, " | ")
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", tag[0], optional, fieldType)
		}
		b.WriteString("}\n")
	}
	if e := os.WriteFile("web/src/lib/types.ts", []byte(b.String()), 0644); e != nil {
		panic(e)
	}
}

func dtoName(t reflect.Type) string {
	if t.PkgPath() == "github.com/OutboundSpade/LabCentral/v2/instructor" {
		switch t.Name() {
		case "Library":
			return "TemplateLibraryMetadata"
		case "Stage":
			return "TemplateStage"
		}
	}
	return t.Name()
}
