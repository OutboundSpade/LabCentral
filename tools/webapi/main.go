// Generate the browser's public DTO contract from hosted types.
package main

import (
	"fmt"
	"github.com/OutboundSpade/LabCentral/v2/hosted"
	"os"
	"reflect"
	"strings"
	"time"
)

func typ(t reflect.Type) string {
	if t == reflect.TypeOf(time.Time{}) {
		return "string"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int:
		return "number"
	case reflect.Pointer:
		return typ(t.Elem()) + " | null"
	case reflect.Slice:
		return typ(t.Elem()) + "[]"
	case reflect.Struct:
		return t.Name()
	}
	panic(t.String())
}
func main() {
	var b strings.Builder
	b.WriteString("// Generated by go run ./tools/webapi. Do not edit.\n")
	for _, v := range []any{hosted.User{}, hosted.Meeting{}, hosted.Team{}, hosted.Membership{}, hosted.Template{}, hosted.Job{}, hosted.Machine{}, hosted.Teammate{}, hosted.LabView{}, hosted.Overview{}, hosted.AdminView{}, hosted.CreateMeeting{}, hosted.JoinTeam{}, hosted.ExtendMeeting{}, hosted.TargetRequest{}, hosted.Launch{}, hosted.ExerciseDefinition{}, hosted.ExerciseRun{}, hosted.ExerciseRequest{}} {
		t := reflect.TypeOf(v)
		fmt.Fprintf(&b, "export interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			if tag[0] == "-" {
				continue
			}
			optional := ""
			if len(tag) > 1 && tag[1] == "omitempty" {
				optional = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", tag[0], optional, typ(f.Type))
		}
		b.WriteString("}\n")
	}
	if e := os.WriteFile("web/src/lib/types.ts", []byte(b.String()), 0644); e != nil {
		panic(e)
	}
}
