// Generate the fresh v2 protobuf model from the public closed command types.
package main

import (
	"fmt"
	lc "github.com/OutboundSpade/LabCentral/v2"
	"os"
	"os/exec"
	"reflect"
	"regexp"
	"strconv"
	"strings"
)

var seen = map[reflect.Type]bool{}
var order []reflect.Type

func visit(t reflect.Type) {
	if t.Kind() == reflect.Pointer {
		visit(t.Elem())
		return
	}
	if t.Kind() == reflect.Slice {
		if t.Elem().Kind() != reflect.Uint8 {
			visit(t.Elem())
		}
		return
	}
	if t.Kind() == reflect.Map {
		visit(t.Elem())
		return
	}
	if t.Kind() != reflect.Struct || seen[t] {
		return
	}
	seen[t] = true
	order = append(order, t)
	for i := 0; i < t.NumField(); i++ {
		visit(t.Field(i).Type)
	}
}
func typ(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		if t.Elem().Kind() == reflect.Struct {
			return typ(t.Elem())
		}
		return "optional " + typ(t.Elem())
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "bool"
	case reflect.Int:
		return "int32"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "bytes"
		}
		return "repeated " + typ(t.Elem())
	case reflect.Map:
		return "map<string, " + typ(t.Elem()) + ">"
	case reflect.Struct:
		return t.Name()
	}
	panic(t.String())
}
func main() {
	for _, v := range []any{lc.Command{}, lc.Result{}, lc.Event{}, lc.Error{}} {
		visit(reflect.TypeOf(v))
	}
	var b strings.Builder
	b.WriteString("// Generated by go run ./tools/protocol. Do not edit.\nsyntax = \"proto3\";\npackage labcentral.plugin.v2;\noption go_package = \"github.com/OutboundSpade/LabCentral/v2/internal/wire;wire\";\nservice Platform { rpc Execute(Request) returns (stream Reply); }\nmessage Request { uint32 version = 1; Command command = 2; }\nmessage Reply { Event event = 1; Result result = 2; Error error = 3; }\n")
	rx := regexp.MustCompile(`([a-z0-9])([A-Z])`)
	for _, t := range order {
		fmt.Fprintf(&b, "message %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			j := strings.Split(f.Tag.Get("json"), ",")[0]
			if j == "" {
				j = f.Name
			}
			name := strings.ToLower(rx.ReplaceAllString(f.Name, "${1}_${2}"))
			number := i + 1
			if tag := f.Tag.Get("proto"); tag != "" {
				number, _ = strconv.Atoi(tag)
			}
			fmt.Fprintf(&b, "  %s %s = %d [json_name = %q];\n", typ(f.Type), name, number, j)
		}
		used := map[int]bool{}
		max := t.NumField()
		for i := 0; i < t.NumField(); i++ {
			number := i + 1
			if tag := t.Field(i).Tag.Get("proto"); tag != "" {
				number, _ = strconv.Atoi(tag)
			}
			used[number] = true
			if number > max {
				max = number
			}
		}
		for i := 1; i <= max; i++ {
			if !used[i] {
				fmt.Fprintf(&b, "  reserved %d;\n", i)
			}
		}
		b.WriteString("}\n")
	}
	if e := os.WriteFile("api/plugin/v2/platform.proto", []byte(b.String()), 0644); e != nil {
		panic(e)
	}
	command := exec.Command("protoc", "--go_out=.", "--go_opt=module=github.com/OutboundSpade/LabCentral/v2", "--go-grpc_out=.", "--go-grpc_opt=module=github.com/OutboundSpade/LabCentral/v2", "api/plugin/v2/platform.proto")
	command.Stdout, command.Stderr = os.Stdout, os.Stderr
	if err := command.Run(); err != nil {
		panic(err)
	}

}
